/**
 * `pnpm tokens` — turns the shared design tokens into a typed theme.
 *
 *   TOKENS_PATH (default ../design/tokens.json)  →  src/theme/tokens.ts (committed)
 *
 * Names become camelCase: `surface-2` → `surface2`, `on-brand` → `onBrand`, `t-title-1` → `title1`.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const src = resolve(root, process.env.TOKENS_PATH ?? '../design/tokens.json');
const out = resolve(root, 'src/theme/tokens.ts');

interface ColorToken {
  name: string;
  value: { light: string; dark: string };
}
interface TypeStyle {
  name: string;
  fontSize: string;
  lineHeight: string;
  fontWeight: number;
  letterSpacing?: string;
}
interface Tokens {
  version: number;
  color: { tokens: ColorToken[] };
  type: { groups: { styles: TypeStyle[] }[] };
  spacing: { tokens: { name: string; value: string }[] };
  radius: { tokens: { name: string; value: string }[] };
  shadow: { tokens: { name: string; value: { light: string; dark: string } }[] };
}

const camel = (s: string) => s.replace(/-([a-z0-9])/g, (_, c: string) => c.toUpperCase());
const px = (v: string) => Number(v.replace('px', ''));

/** Inter ships static weights; React Native picks the face by family name, not fontWeight. */
const INTER: Record<number, string> = {
  400: 'Inter_400Regular',
  500: 'Inter_500Medium',
  600: 'Inter_600SemiBold',
  700: 'Inter_700Bold',
};
const interFamily = (w: number) => INTER[w] ?? INTER[w >= 650 ? 600 : 500]!;

const t = JSON.parse(readFileSync(src, 'utf8')) as Tokens;

const colors = { light: {} as Record<string, string>, dark: {} as Record<string, string> };
for (const c of t.color.tokens) {
  colors.light[camel(c.name)] = c.value.light;
  colors.dark[camel(c.name)] = c.value.dark;
}

const space: Record<string, number> = {};
for (const s of t.spacing.tokens) space[camel(s.name).replace(/^s(\d)/, 's$1')] = px(s.value);

const radius: Record<string, number> = {};
for (const r of t.radius.tokens) radius[r.name.replace(/^r-/, '')] = px(r.value);

const type: Record<string, object> = {};
for (const g of t.type.groups) {
  for (const s of g.styles) {
    const key = camel(s.name.replace(/^t-/, ''));
    type[key] = {
      fontFamily: interFamily(s.fontWeight),
      fontSize: px(s.fontSize),
      lineHeight: px(s.lineHeight),
      ...(s.letterSpacing ? { letterSpacing: px(s.letterSpacing) } : {}),
    };
  }
}

const shadow = t.shadow.tokens.find((s) => s.name === 'shadow-float');
if (!shadow) throw new Error('shadow-float missing from tokens.json');

const body = `// Generated by \`pnpm tokens\` from design/tokens.json (v${t.version}). Do not edit by hand.

export const colors = ${JSON.stringify(colors, null, 2)} as const;

export type ColorScheme = keyof typeof colors;
export type ColorName = keyof (typeof colors)['light'];
export type Colors = { readonly [K in ColorName]: string };

export const space = ${JSON.stringify(space, null, 2)} as const;

export const radius = ${JSON.stringify(radius, null, 2)} as const;

export const type = ${JSON.stringify(type, null, 2)} as const;

export type TypeStyle = keyof typeof type;

/** CSS box-shadow strings (React Native supports \`boxShadow\`). Only for floating layers. */
export const shadowFloat = ${JSON.stringify(shadow.value, null, 2)} as const;

export const fonts = ${JSON.stringify(INTER, null, 2)} as const;
`;

writeFileSync(out, body);
console.log(`tokens: ${t.color.tokens.length} colours, ${Object.keys(type).length} type styles → ${out}`);
