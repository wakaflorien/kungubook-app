/**
 * `pnpm api:sync` — copy the current API contract into this repo and regenerate the typed client.
 *
 *   API_SPEC_URL   the backend's published spec (e.g. https://staging-api.kungubook.app/v1/openapi.json)
 *   SPEC_PATH      a local spec (default: ../docs/openapi.yaml, the app team's draft)
 *
 * Writes src/api/openapi.yaml (committed copy, also served by `pnpm mock`) and src/api/schema.d.ts.
 * `pnpm api:sync --check` regenerates from the committed copy and fails if schema.d.ts is stale (CI).
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, relative, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const specOut = resolve(root, 'src/api/openapi.yaml');
const typesOut = resolve(root, 'src/api/schema.d.ts');
const check = process.argv.includes('--check');

async function readSource(): Promise<{ text: string; from: string }> {
  const url = process.env.API_SPEC_URL;
  if (url) {
    const res = await fetch(url);
    if (!res.ok) throw new Error(`GET ${url} → ${res.status}`);
    // JSON is valid YAML, so a published openapi.json can be stored as openapi.yaml unchanged.
    return { text: await res.text(), from: url };
  }
  const path = resolve(root, process.env.SPEC_PATH ?? '../docs/openapi.yaml');
  if (!existsSync(path)) throw new Error(`No spec at ${path}. Set SPEC_PATH or API_SPEC_URL.`);
  return { text: readFileSync(path, 'utf8'), from: relative(root, path) };
}

const HEADER = `/**
 * Generated by \`pnpm api:sync\` from src/api/openapi.yaml with openapi-typescript.
 * Do not edit by hand.
 */

`;

async function generate(): Promise<string> {
  const ast = await openapiTS(pathToFileURL(specOut), {
    alphabetize: false,
    exportType: false,
    defaultNonNullable: false,
  });
  return HEADER + astToString(ast);
}

async function main() {
  if (check) {
    const fresh = await generate();
    const current = existsSync(typesOut) ? readFileSync(typesOut, 'utf8') : '';
    if (fresh !== current) {
      console.error('src/api/schema.d.ts is out of date with src/api/openapi.yaml. Run `pnpm api:sync`.');
      process.exit(1);
    }
    console.log('api:sync --check: schema.d.ts matches src/api/openapi.yaml');
    return;
  }

  const { text, from } = await readSource();
  writeFileSync(specOut, text);
  writeFileSync(typesOut, await generate());
  console.log(`api:sync: ${from} → src/api/openapi.yaml + src/api/schema.d.ts`);
}

main().catch((err: unknown) => {
  console.error(err instanceof Error ? err.message : err);
  process.exit(1);
});
